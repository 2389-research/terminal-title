#!/bin/bash
# ABOUTME: Installs the set-terminal-title wrapper into ~/.local/bin for non-Claude-Code harnesses
# ABOUTME: Creates a stable executable path that harnesses (e.g. Codex) can approve as a command prefix

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/.." && pwd)"
SET_TITLE_SCRIPT="${REPO_ROOT}/skills/scripts/set_title.sh"

if [ ! -f "$SET_TITLE_SCRIPT" ]; then
    echo "error: set_title.sh not found at ${SET_TITLE_SCRIPT}" >&2
    echo "run this script from inside a checkout of the terminal-title repo" >&2
    exit 1
fi

INSTALL_DIR="${HOME}/.local/bin"
WRAPPER="${INSTALL_DIR}/set-terminal-title"

mkdir -p "$INSTALL_DIR"

# The wrapper hardcodes the resolved absolute path so harness command-prefix
# approvals stay stable even if the skill internals move within the repo.
cat > "$WRAPPER" <<EOF
#!/bin/bash
# ABOUTME: Stable entry point for terminal-title — generated by bin/install.sh
# ABOUTME: Hides the underlying set_title.sh path so harness approvals remain valid
exec bash "${SET_TITLE_SCRIPT}" "\$@"
EOF

chmod +x "$WRAPPER"

echo "installed: ${WRAPPER}"
echo "  -> ${SET_TITLE_SCRIPT}"

case ":${PATH}:" in
    *":${INSTALL_DIR}:"*)
        ;;
    *)
        echo
        echo "note: ${INSTALL_DIR} is not on your PATH."
        echo "add this to your shell profile:"
        echo "  export PATH=\"\${HOME}/.local/bin:\${PATH}\""
        ;;
esac
